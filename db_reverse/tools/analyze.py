def read_text(p):
    raw = open(p, 'rb').read()
    for enc in ('utf-8', 'cp1251'):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            pass
    return raw.decode('latin-1')

lit_re = re.compile(r'"((?:[^"\n]|"")*)"')
