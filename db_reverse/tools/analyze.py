def split_top(s):
    parts, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts

orm_raw = open(os.path.join(OUT, '01_orm_schema.sql'), encoding='utf-8-sig').read()
orm_tables = {}   # TABLE -> {COL: type}
orm_pk = {}
pretty = []
if not orm_raw.startswith('/*'):
    seen_tables = set()
    for stmt in [x.strip() for x in orm_raw.split('\nGO') if x.strip()]:
        m = re.match(r'create table (\w+) \((.*)\)$', stmt, re.S | re.I)
        if m and m.group(1).upper() in seen_tables:
            pretty.append(f'-- NOTE: {m.group(1)} is mapped twice (case differs, same table on a CI collation); duplicate skipped:\n-- ' + stmt + '\n')
            continue
        if m:
            seen_tables.add(m.group(1).upper())
            items = split_top(m.group(2))
            pkm = [x for x in items if re.match(r'primary key', x, re.I)]
            pk_cols = {c.strip().upper() for c in re.search(r'\((.*)\)', pkm[0]).group(1).split(',')} if pkm else set()
            fixed = []
            for it in items:
                # mapping bug: .Check("PK_X") used as if it were a constraint name -> invalid CHECK
                it = re.sub(r'\s*check\(\s*\w+\s*\)$', '', it, flags=re.I)
                cm = re.match(r'(\w+)(\s+.*)$', it, re.S)
                if cm and not re.match(r'(primary|unique|constraint|foreign|check)\b', it, re.I):
                    col, rest = cm.group(1), cm.group(2)
                    if col.upper() in pk_cols:
                        rest = re.sub(r'\bnull$', 'not null', rest) if not re.search(r'not null$', rest, re.I) else rest
                    if col.upper() in TSQL_RESERVED:
                        col = f'[{col}]'
                    it = col + rest
                elif re.match(r'(primary key|unique)\s*\(', it, re.I):
                    head, cols_ = it.split('(', 1)
                    it = head + '(' + re.sub(r'\b(\w+)\b', lambda mm: f'[{mm.group(1)}]' if mm.group(1).upper() in TSQL_RESERVED else mm.group(1), cols_)
                fixed.append(it)
            items = fixed
            pretty.append(f'CREATE TABLE dbo.{m.group(1)} (\n    ' + ',\n    '.join(items) + '\n);\nGO\n')
        else:
            pretty.append(stmt + ';\nGO\n')
